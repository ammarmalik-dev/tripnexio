/**
 * Prints the SQL that loads the client's status lists + templates (client doc 2026-10-20) from
 * src/lib/service-status/catalog.ts and template-catalog.json — the source of migration
 * 20261021090000_client_status_lists. Run: `npx tsx scripts/status-catalog-sql.ts > migration.sql`.
 *
 * Per service and scope it: renames the first earlier status still present onto each new name (its id,
 * history and transitions stay), upserts every status with the client's label / notify / flags,
 * moves records off the other earlier names, deactivates whatever is no longer on the list, adds the
 * forward transitions, and inserts the templates (never overwriting an Admin-edited row).
 */
import { STATUS_CATALOG, type CatalogStatus } from "../src/lib/service-status/catalog";
import templates from "../src/lib/service-status/template-catalog.json";

const q = (value: string | null | undefined) => (value === null || value === undefined ? "NULL" : `'${value.replace(/'/g, "''")}'`);
const REFUND_EVENTS = new Set(["REFUND_RAISED", "REFUND_APPROVED", "REFUND_COMPLETED", "CANCELLED_AND_REFUNDED"]);
const out: string[] = [];
const push = (sql: string) => out.push(sql.trim() + "\n");

push(`-- Client doc 2026-10-20 — every service's final status list and per-status email / WhatsApp templates.
-- Generated by scripts/status-catalog-sql.ts from src/lib/service-status/catalog.ts + template-catalog.json.
ALTER TABLE "Booking" ADD COLUMN IF NOT EXISTS "resumeServiceStatusId" TEXT;
ALTER TABLE "NotificationTemplate" ADD COLUMN IF NOT EXISTS "heading" TEXT;
ALTER TABLE "NotificationTemplate" ADD COLUMN IF NOT EXISTS "ctaLabel" TEXT;
ALTER TABLE "NotificationTemplate" ADD COLUMN IF NOT EXISTS "ctaLink" TEXT;`);

for (const list of STATUS_CATALOG) {
  const where = `"serviceType" = '${list.serviceType}' AND "scope" = '${list.scope}'`;
  const isLead = list.scope === "LEAD";
  push(`\n-- ── ${list.serviceType} / ${list.scope}`);
  // System events are re-assigned below — clear them first so two rows never claim the same event.
  push(`UPDATE "ServiceStatus" SET "systemEvent" = NULL WHERE ${where};`);

  list.statuses.forEach((status: CatalogStatus, index) => {
    const olds = (status.from ?? []).filter((name) => name !== status.name);
    if (olds.length > 0) {
      push(`UPDATE "ServiceStatus" SET "name" = ${q(status.name)}
WHERE "id" = (
  SELECT "id" FROM "ServiceStatus" WHERE ${where} AND "name" IN (${olds.map(q).join(", ")})
  ORDER BY array_position(ARRAY[${olds.map(q).join(", ")}]::text[], "name") LIMIT 1
) AND NOT EXISTS (SELECT 1 FROM "ServiceStatus" WHERE ${where} AND "name" = ${q(status.name)});`);
    }
    const maps = status.maps ?? null;
    push(`INSERT INTO "ServiceStatus" ("id", "serviceType", "scope", "name", "displayOrder", "isTerminal", "blocksRefund", "customerLabel", "mapsToLeadStatus", "mapsToBookingStatus", "notificationEvent", "systemEvent", "active", "createdAt", "updatedAt")
VALUES ('ss_' || md5('${list.serviceType}/${list.scope}/' || ${q(status.name)}), '${list.serviceType}', '${list.scope}', ${q(status.name)}, ${index * 10}, ${status.terminal ? "true" : "false"}, ${status.blocksRefund ? "true" : "false"}, ${q(status.customerLabel)}, ${isLead && maps ? `'${maps}'` : "NULL"}, ${!isLead && maps ? `'${maps}'` : "NULL"}, ${q(status.notify)}, ${q(status.systemEvent ?? null)}, true, now(), now())
ON CONFLICT ("serviceType", "scope", "name") DO UPDATE SET
  "displayOrder" = EXCLUDED."displayOrder", "isTerminal" = EXCLUDED."isTerminal", "blocksRefund" = EXCLUDED."blocksRefund",
  "customerLabel" = EXCLUDED."customerLabel", "mapsToLeadStatus" = EXCLUDED."mapsToLeadStatus", "mapsToBookingStatus" = EXCLUDED."mapsToBookingStatus",
  "notificationEvent" = EXCLUDED."notificationEvent", "systemEvent" = EXCLUDED."systemEvent", "active" = true, "updatedAt" = now();`);
    if (olds.length > 0) {
      const table = isLead ? "Lead" : "Booking";
      const coarse = maps ? `, "status" = '${maps}'` : "";
      push(`UPDATE "${table}" SET "serviceStatusId" = (SELECT "id" FROM "ServiceStatus" WHERE ${where} AND "name" = ${q(status.name)})${coarse}
WHERE "serviceStatusId" IN (SELECT "id" FROM "ServiceStatus" WHERE ${where} AND "name" IN (${olds.map(q).join(", ")}));`);
    }
  });

  const names = list.statuses.map((status) => q(status.name)).join(", ");
  push(`UPDATE "ServiceStatus" SET "active" = false, "systemEvent" = NULL, "notificationEvent" = NULL WHERE ${where} AND "name" NOT IN (${names});`);

  // Transitions: forward along the list, into and out of On Hold, and from a final status on to the refund steps.
  const pairs: [string, string][] = [];
  const holdName = list.statuses.find((status) => status.systemEvent === "ON_HOLD")?.name;
  list.statuses.forEach((from, i) => {
    list.statuses.forEach((to, j) => {
      if (from.name === to.name) return;
      if (from.systemEvent === "ON_HOLD") {
        if (!to.terminal || REFUND_EVENTS.has(to.systemEvent ?? "")) pairs.push([from.name, to.name]);
        return;
      }
      if (to.name === holdName) {
        if (!from.terminal) pairs.push([from.name, to.name]);
        return;
      }
      if (from.terminal) {
        if (REFUND_EVENTS.has(to.systemEvent ?? "") && j > i) pairs.push([from.name, to.name]);
        return;
      }
      if (j > i) pairs.push([from.name, to.name]);
    });
  });
  if (pairs.length > 0) {
    push(`INSERT INTO "ServiceStatusTransition" ("id", "fromStatusId", "toStatusId")
SELECT 'sst_' || md5(f."id" || '>' || t."id"), f."id", t."id"
FROM (VALUES
${pairs.map(([a, b]) => `  (${q(a)}, ${q(b)})`).join(",\n")}
) AS p("fromName", "toName")
JOIN "ServiceStatus" f ON f."serviceType" = '${list.serviceType}' AND f."scope" = '${list.scope}' AND f."name" = p."fromName"
JOIN "ServiceStatus" t ON t."serviceType" = '${list.serviceType}' AND t."scope" = '${list.scope}' AND t."name" = p."toName"
ON CONFLICT ("fromStatusId", "toStatusId") DO NOTHING;`);
  }
}

push(`\n-- ── Templates (one EMAIL + one WHATSAPP row per notifying status; an existing row is left as the Admin edited it)`);
for (const template of templates as { event: string; channel: string; subject: string | null; heading: string | null; body: string; ctaLabel: string | null; ctaLink: string | null }[]) {
  push(`INSERT INTO "NotificationTemplate" ("id", "event", "channel", "subject", "body", "active", "heading", "ctaLabel", "ctaLink", "createdAt", "updatedAt")
VALUES ('nt_' || md5('${template.event}/${template.channel}'), ${q(template.event)}, '${template.channel}', ${q(template.subject)}, ${q(template.body)}, true, ${q(template.heading)}, ${q(template.ctaLabel)}, ${q(template.ctaLink)}, now(), now())
ON CONFLICT ("event", "channel") DO NOTHING;`);
}

process.stdout.write(out.join("\n"));
